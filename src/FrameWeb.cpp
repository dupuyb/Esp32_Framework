// ===== Internal zip helper utilities (local to this translation unit) =====
// Purpose:
// - Convert compressed bytes to/from ASCII hex representation.
// - Detect whether a generated chunk is in FrameWeb zip format.

char nibbleToHex(uint8_t nibble) {
  return (nibble < 10) ? static_cast<char>('0' + nibble) : static_cast<char>('A' + (nibble - 10));
}

int hexToNibble(char ch) {
  if (ch >= '0' && ch <= '9') {
    return ch - '0';
  }
  if (ch >= 'a' && ch <= 'f') {
    return 10 + (ch - 'a');
  }
  if (ch >= 'A' && ch <= 'F') {
    return 10 + (ch - 'A');
  }
  return -1;
}

String bytesToHex(const uint8_t* data, size_t length) {
  String hex;
  if (!hex.reserve(length * 2)) {
    return String();
  }

  for (size_t index = 0; index < length; ++index) {
    const uint8_t value = data[index];
    hex += nibbleToHex((value >> 4) & 0x0F);
    hex += nibbleToHex(value & 0x0F);
  }

  return hex;
}

bool hexToBytes(const String& hex, uint8_t* output, size_t outputLength) {
  if ((hex.length() % 2) != 0 || (hex.length() / 2) != outputLength) {
    return false;
  }

  for (size_t index = 0; index < outputLength; ++index) {
    const int high = hexToNibble(hex[index * 2]);
    const int low = hexToNibble(hex[(index * 2) + 1]);
    if (high < 0 || low < 0) {
      return false;
    }
    output[index] = static_cast<uint8_t>((high << 4) | low);
  }

  return true;
}

bool isZippedString(const String& payload) {
  // Fast format detection for FrameWeb zip payloads:
  // "<raw_size>:<hex_zlib_payload>"
  // Current strategy validates only the numeric size prefix and ':' separator
  // to keep this check very cheap for all HTTP_* chunk reads.
  const int separator = payload.indexOf(':');
  if (separator <= 0) {
    return false;
  }

  for (int i = 0; i < separator; ++i) {
    const char ch = payload[i];
    if (ch < '0' || ch > '9') {
      return false;
    }
  }
  /*
  Optional strict validation (kept disabled for speed):
  - Enforces even hex payload length.
  - Validates each payload character is a hex digit.

  const String hexPart = payload.substring(separator + 1);
  if ((hexPart.length() % 2) != 0) {
    return false;
  }

  for (size_t i = 0; i < hexPart.length(); ++i) {
    const char ch = hexPart[i];
    const bool isHexDigit =
      (ch >= '0' && ch <= '9') ||
      (ch >= 'a' && ch <= 'f') ||
      (ch >= 'A' && ch <= 'F');
    if (!isHexDigit) {
      return false;
    }
  }
*/
  return true;
}

