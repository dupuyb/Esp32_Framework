String FrameWeb::zipString(const String& input) {
  // Encode plain text to FrameWeb payload format:
  //   <original_size>:<HEX-ENCODED-ZLIB-BYTES>
  // Implementation detail:
  // - Uses low-level tdefl API.
  // - Allocates compressor state on heap to avoid ROM internal MZ_MALLOC path,
  //   which can fail on ESP32-S3 without PSRAM (~164KB compressor structure).
  const size_t sourceLength = input.length();
  const String header = String(static_cast<unsigned long>(sourceLength)) + ":";

  if (sourceLength == 0) {
    return header;
  }

  const int compressFlags = TDEFL_WRITE_ZLIB_HEADER | TDEFL_DEFAULT_MAX_PROBES;
  const size_t outCapacity = sourceLength + (sourceLength / 10) + 256;

  std::unique_ptr<uint8_t[]> outBuf(new (std::nothrow) uint8_t[outCapacity]);
  std::unique_ptr<tdefl_compressor> comp(new (std::nothrow) tdefl_compressor());

  if (!outBuf || !comp) {
    FDBXERR("zipString: allocation failed (heap pressure). freeHeap=%u\n\r", ESP.getFreeHeap());
    return String();
  }

  if (tdefl_init(comp.get(), nullptr, nullptr, compressFlags) != TDEFL_STATUS_OKAY) {
    FDBXERR("zipString: init failed.");
    return String();
  }

  size_t inSize = sourceLength;
  size_t outSize = outCapacity;
  const tdefl_status status = tdefl_compress(comp.get(),
    reinterpret_cast<const void*>(input.c_str()), &inSize,
    outBuf.get(), &outSize,
    TDEFL_FINISH);

  if (status != TDEFL_STATUS_DONE) {
    FDBXERR("zipString: compression failed. status=%s\n\r",String((int)status));
    return String();
  }

  // outSize is remaining free bytes after compression.
  const size_t compressedLength = outCapacity - outSize;
  return header + bytesToHex(outBuf.get(), compressedLength);
}

String FrameWeb::unzipString(const String& input) {
  // Decode FrameWeb payload format:
  //   <original_size>:<HEX-ENCODED-ZLIB-BYTES>
  // Implementation detail:
  // - Uses tinfl_decompress.
  // - Allocates tinfl_decompressor on heap because the ROM helper
  //   tinfl_decompress_mem_to_mem() uses large stack state on ESP32-S3.
  const int separator = input.indexOf(':');
  if (separator < 0) {
    FDBXLN(F("unzipString invalid payload header."));
    return String();
  }

  const String sizeToken = input.substring(0, separator);
  for (size_t i = 0; i < sizeToken.length(); ++i) {
    if (sizeToken[i] < '0' || sizeToken[i] > '9') {
      FDBXLN(F("unzipString invalid size token."));
      return String();
    }
  }

  const size_t expectedLength = static_cast<size_t>(strtoul(sizeToken.c_str(), nullptr, 10));
  const String hexPayload = input.substring(separator + 1);
  if (expectedLength == 0) {
    return hexPayload.length() == 0 ? String("") : String();
  }

  if ((hexPayload.length() % 2) != 0) {
    FDBXLN(F("unzipString invalid hex payload length (must be even)."));
    return String();
  }

  const size_t compressedLength = hexPayload.length() / 2;
  std::unique_ptr<uint8_t[]> compressed(new uint8_t[compressedLength]);
  if (!hexToBytes(hexPayload, compressed.get(), compressedLength)) {
    FDBXLN(F("unzipString invalid hex payload."));
    return String();
  }

  std::unique_ptr<uint8_t[]> output(new uint8_t[expectedLength + 1]);

  // Allocate tinfl_decompressor on heap to avoid stack overflow:
  // tinfl_decompress_mem_to_mem() allocates tinfl_decompressor (~11KB) on the ROM stack,
  // which overflows the loopTask default 8KB stack on ESP32-S3.
  std::unique_ptr<tinfl_decompressor> decomp(new (std::nothrow) tinfl_decompressor());
  if (!decomp) {
    FDBXERR("unzipString: decompressor alloc failed. freeHeap=%u\n\r", ESP.getFreeHeap());
    return String();
  }
  tinfl_init(decomp.get());

  size_t inBufSize = compressedLength;
  size_t outBufSize = expectedLength;
  const tinfl_status tstatus = tinfl_decompress(
    decomp.get(),
    compressed.get(), &inBufSize,
    output.get(), output.get(), &outBufSize,
    TINFL_FLAG_PARSE_ZLIB_HEADER | TINFL_FLAG_USING_NON_WRAPPING_OUTPUT_BUF
  );

  const size_t outputLength = (tstatus == TINFL_STATUS_DONE) ? outBufSize : 0;

  if (outputLength == 0 || outputLength != expectedLength) {
    FDBXLN("unzipString decompression failed. status=" + String((int)tstatus)
      + " inUsed=" + String(inBufSize)
      + " outLen=" + String(outputLength)
      + " expected=" + String(expectedLength));
    return String();
  }

  output[outputLength] = '\0';
  return String(reinterpret_cast<char*>(output.get()));
}

String FrameWeb::decodeHtmlChunk(const char* chunk) {
  // Unified read path for generated HTTP_* chunks.
  // Handles both plain HTML and FrameWeb zip payload transparently.
  // Safety fallback: if payload looks zipped but decode fails, return raw
  // chunk to avoid blank built-in pages.
  const String raw = FPSTR(chunk);
  FDBXLN("decodeHtmlChunk len="+String(raw.length())+" zipped="+String(isZippedString(raw)));
  if (!isZippedString(raw)) {
    return raw;
  }

  const String decoded = unzipString(raw);

  // Keep raw payload when decode fails to avoid returning an empty page fragment.
  return (decoded.length() == 0 && raw != "0:") ? raw : decoded;
}


// Handle Web server ----- used in startWebServer -------------------------------------------------------------------
bool FrameWeb::handleFileRead(String path) {               // send the right file to the client (if it exists)
  FDBXLN("handleFileRead path:" + path);
  if (path.endsWith("/")) path += "index.html";            // If a folder is requested, send the index file
  String contentType = getContentType(path);               // Get the MIME type
  String pathWithGz = path + ".gz";
  if (SPIFFS.exists(pathWithGz) || SPIFFS.exists(path)) {  // If the file exists, either as a compressed archive, or normal
    if (SPIFFS.exists(pathWithGz))                         // If there's a compressed version available
      path += ".gz";                                       // Use the compressed verion
    File file = SPIFFS.open(path, "r");                    // Open the file
    server.streamFile(file, contentType);                  // Send it to the client
    file.close();                                          // Close the file again
    FDBXLN("\tSent file: " + path);
    return true;
  } else {                                                 // Otherwise build answer locally
    if (config.UseToolsLocal) {
      if (path.endsWith("/index.html")){  // Tools                 // For default index.html page after authentification
        if (!server.authenticate(config.LoginName, config.LoginPassword)) {
           server.requestAuthentication();
           return true;
        }
        server.send(200, "text/html", simpleIndex() );     // If not upload.html in FS send light
        return true;
      }
      if (path.endsWith("/update")){                       // return index page which is stored in serverIndex
        if (!server.authenticate(config.LoginName, config.LoginPassword)) {
          server.requestAuthentication();
          return true;
        }
        server.sendHeader("Connection", "close");
        server.send(200, "text/html", simpleFirmware());
        return true;
      }
    }
  }
  FDBXLN("\tFile Not Found: " + path);                  // If the file doesn't exist, return false
  return false;
}

void FrameWeb::handleFileUpload(){                      // upload a new file to the SPIFFS
  HTTPUpload& upload = server.upload();
  String path;
  if(upload.status == UPLOAD_FILE_START){
    path = upload.filename;
    if ( path.length() < 3 ) {
      server.send(500, "text/plain", "Couldn't create file:["+path+"] invalid name.");
      return;
    }
    if(!path.startsWith("/")) path = "/"+path;
    if(!path.endsWith(".gz")) {                          // The file server always prefers a compressed version of a file
      String pathWithGz = path+".gz";                    // So if an uploaded file is not compressed, the existing compressed
      if(SPIFFS.exists(pathWithGz))                      // version of that file must be deleted (if it exists)
         SPIFFS.remove(pathWithGz);
    }
    FDBXMF("handleFileUpload Name: %s\n\r", path.c_str());
    fsUploadFile = SPIFFS.open(path, "w");               // Open the file for writing in SPIFFS (create if it doesn't exist)
    path = String();
  } else if(upload.status == UPLOAD_FILE_WRITE){
    if(fsUploadFile)
      fsUploadFile.write(upload.buf, upload.currentSize); // Write the received bytes to the file
  } else if(upload.status == UPLOAD_FILE_END){
    if(fsUploadFile) {                                    // If the file was successfully created
      fsUploadFile.close();                               // Close the file again
      FDBXMF("handleFileUpload Size: %d\n\r", upload.totalSize);
      server.sendHeader("Location","/success.html");      // Redirect the client to the success page
      server.send(303);
    } else {
      server.send(500, "text/plain", "Couldn't upload file:["+path+"] in SPIFFS.");
    }
  }
}

